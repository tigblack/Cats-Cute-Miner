#!/usr/bin/env python3
"""Генерирует Assets/Game/Scripts/Runtime/Pixel/PixelPalette.g.cs из RAMPS в pxl.py (запускается и из build.py).

Кроме полей <Рампа><индекс> (Navy3, FurGinger2 …) пишет словарь PixelPalette.ByName: имя тона как ключ PALETTE в pxl.py
("cream4", "fur_ginger2", а также "white" и "black") → Color. По нему вид находит цвет из конфигов, например Color полосы
трубы товара в factory_rules.json (ТЗ 2.2 §3.2).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import pxl  # noqa: E402

OUT = os.path.join(ROOT, 'Assets', 'Game', 'Scripts', 'Runtime', 'Pixel', 'PixelPalette.g.cs')


def _camel(ramp: str) -> str:
    return ''.join(p.capitalize() for p in ramp.split('_'))


def main() -> None:
    lines = ['// <auto-generated>', '// Сгенерировано Tools/PixelArt/gen_palette.py из RAMPS в pxl.py — не редактировать вручную.', '// </auto-generated>',
             'using System.Collections.Generic;', 'using UnityEngine;', '', 'namespace CatMiners.Runtime', '{',
             '    /// <summary>Палитра пиксель-арта (Docs/Art/PIXEL_STYLE_GUIDE.md, раздел 2): те же цвета, что у спрайтов. Рампы от тёмного к светлому.</summary>',
             '    public static class PixelPalette', '    {']
    for ramp, cols in pxl.RAMPS.items():
        camel = _camel(ramp)
        for i, h in enumerate(cols):
            r, g, b = pxl._hex(h)
            lines.append(f'        public static readonly Color {camel}{i} = new Color32({r}, {g}, {b}, 255);')
        lines.append('')
    # Словарь по имени — после всех полей (статические поля инициализируются по порядку текста).
    lines += [
        '        /// <summary>',
        '        /// Тон по имени, как ключи PALETTE в Tools/PixelArt/pxl.py: "&lt;рампа&gt;&lt;индекс&gt;" ("cream4", "fur_ginger2"), а также',
        '        /// "white" и "black". Для цветов из конфигов: Color полосы трубы в factory_rules.json (ТЗ 2.2 §3.2). Регистр важен.',
        '        /// </summary>',
        '        public static readonly IReadOnlyDictionary<string, Color> ByName = new Dictionary<string, Color>(System.StringComparer.Ordinal)',
        '        {',
    ]
    for ramp, cols in pxl.RAMPS.items():
        camel = _camel(ramp)
        lines.append('            ' + ' '.join(f'{{ "{ramp}{i}", {camel}{i} }},' for i in range(len(cols))))
    lines += [
        '            { "white", new Color32(255, 255, 255, 255) }, { "black", new Color32(0, 0, 0, 255) },',
        '        };',
        '',
        '        /// <summary>Тон по имени (см. <see cref="ByName"/>); false — имени нет в палитре, тогда color — белый.</summary>',
        '        public static bool TryGet(string name, out Color color)',
        '        {',
        '            if (name != null && ByName.TryGetValue(name, out color)) return true;',
        '            color = Color.white;',
        '            return false;',
        '        }',
        '    }', '}', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
