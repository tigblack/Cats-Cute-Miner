#!/usr/bin/env python3
"""Генерирует OutpostConfigSet.Defaults.cs из Assets/Game/Resources/Outpost/*.json.

Встроенные строки ядра должны побайтно совпадать с файлами Resources (тесты сравнивают их).
Запуск из корня проекта: python3 Tools/gen_outpost_config_defaults.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'Assets', 'Game', 'Resources', 'Outpost')
OUT = os.path.join(ROOT, 'Assets', 'Game', 'Scripts', 'Core', 'Outpost', 'Config', 'OutpostConfigSet.Defaults.cs')
FILES = [
    ('DefaultBalanceJson', 'outpost_balance.json'),
    ('DefaultEquipmentJson', 'equipment_catalog.json'),
    ('DefaultRewardsJson', 'stage_rewards.json'),
    ('DefaultOverridesJson', 'level_overrides.json'),
    ('DefaultCardRulesJson', 'card_rules.json'),
    ('DefaultTopologyJson', 'mine_topology.json'),
    ('DefaultStoreJson', 'store_catalog.json'),
    ('DefaultFactoryRulesJson', 'factory_rules.json'),
    ('DefaultDressingJson', 'mine_dressing.json'),
    ('DefaultProgressionJson', 'progression.json'),
    ('DefaultFinalExcavationsJson', 'final_excavations.json'),
]


def main():
    parts = [
        '// <auto-generated> Tools/gen_outpost_config_defaults.py из Assets/Game/Resources/Outpost/*.json — не править вручную.',
        '',
        'namespace CatMiners.Core.Outpost',
        '{',
        '    public sealed partial class OutpostConfigSet',
        '    {',
    ]
    for name, fname in FILES:
        with open(os.path.join(SRC, fname), 'r', encoding='utf-8', newline='') as f:
            text = f.read()
        if '\r' in text:
            raise SystemExit(fname + ': ожидались переводы строк LF')
        literal = text.replace('"', '""')
        parts.append('        /// <summary>Встроенная копия Resources/Outpost/' + fname + '.</summary>')
        parts.append('        public const string ' + name + ' = @"' + literal + '";')
        parts.append('')
    parts[-1:] = ['    }', '}', '']
    data = '\n'.join(parts)
    with open(OUT, 'w', encoding='utf-8', newline='') as f:
        f.write(data)
    print('written', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
